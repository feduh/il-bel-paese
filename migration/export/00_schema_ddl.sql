-- Genera lo schema completo del database (schema "public" + policy dello storage + bucket + job pianificati)
-- come un unico script SQL, partendo dallo stato REALE del database e non dalle 76 migrazioni.
-- Serve perché le migrazioni non si riapplicano da zero: alcune inseriscono dati che non esistono più
-- e altre creano account di prova con password scritte nel codice.
--
-- Uso: lanciare la query; il risultato (una sola cella di testo) va salvato come baseline.sql.
-- Si applica su un Supabase appena installato, prima di importare i dati.
WITH
enums AS (
  SELECT string_agg(format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
           (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder) FROM pg_enum e WHERE e.enumtypid = t.oid)),
         E'\n' ORDER BY t.typname) AS sql
  FROM pg_type t WHERE t.typnamespace = 'public'::regnamespace AND t.typtype = 'e'
),
tabs AS (
  SELECT string_agg(format(E'CREATE TABLE public.%I (\n%s\n);', c.relname,
           (SELECT string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                     CASE WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                          WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
                     CASE WHEN a.attgenerated = 's' THEN format(' GENERATED ALWAYS AS (%s) STORED', pg_get_expr(d.adbin, d.adrelid))
                          WHEN d.adbin IS NOT NULL AND a.attidentity = '' THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END,
                     CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END), E',\n' ORDER BY a.attnum)
            FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped)),
         E'\n\n' ORDER BY c.relname) AS sql
  FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
),
funcs AS (
  SELECT string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' ORDER BY p.proname, p.oid) AS sql
  FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f', 'p')
),
cons AS (
  SELECT string_agg(format('ALTER TABLE %s ADD CONSTRAINT %I %s;', con.conrelid::regclass, con.conname, pg_get_constraintdef(con.oid)),
         E'\n' ORDER BY CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END,
                        con.conrelid::regclass::text, con.conname) AS sql
  FROM pg_constraint con
  WHERE con.connamespace = 'public'::regnamespace AND con.conrelid <> 0
),
idx AS (
  SELECT string_agg(i.indexdef || ';', E'\n' ORDER BY i.indexname) AS sql
  FROM pg_indexes i
  WHERE i.schemaname = 'public'
    AND NOT EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = (quote_ident(i.schemaname) || '.' || quote_ident(i.indexname))::regclass)
),
rls AS (
  SELECT string_agg(format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', c.relname)
           || CASE WHEN c.relforcerowsecurity THEN format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', c.relname) ELSE '' END,
         E'\n' ORDER BY c.relname) AS sql
  FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND c.relrowsecurity
),
pols AS (
  SELECT string_agg(
           format('DROP POLICY IF EXISTS %I ON %I.%I;', p.policyname, p.schemaname, p.tablename) || E'\n' ||
           format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', p.policyname, p.schemaname, p.tablename,
             p.permissive, p.cmd, (SELECT string_agg(quote_ident(r), ', ') FROM unnest(p.roles) r),
             CASE WHEN p.qual IS NOT NULL THEN E'\n  USING (' || p.qual || ')' ELSE '' END,
             CASE WHEN p.with_check IS NOT NULL THEN E'\n  WITH CHECK (' || p.with_check || ')' ELSE '' END),
         E'\n' ORDER BY p.schemaname, p.tablename, p.policyname) AS sql
  FROM pg_policies p WHERE p.schemaname IN ('public', 'storage')
),
trigs AS (
  SELECT string_agg(pg_get_triggerdef(t.oid) || ';' ||
           CASE WHEN t.tgenabled = 'D' THEN format(E'\nALTER TABLE %s DISABLE TRIGGER %I;', t.tgrelid::regclass, t.tgname) ELSE '' END,
         E'\n' ORDER BY t.tgrelid::regclass::text, t.tgname) AS sql
  FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
  WHERE NOT t.tgisinternal AND c.relnamespace = 'public'::regnamespace
),
tgrants AS (
  SELECT string_agg(format('REVOKE ALL ON public.%I FROM anon, authenticated, service_role;', c.relname) ||
           coalesce((SELECT E'\n' || string_agg(format('GRANT %s ON public.%I TO %I;', g.privs, c.relname, g.grantee), E'\n' ORDER BY g.grantee)
                     FROM (SELECT grantee, string_agg(privilege_type, ', ' ORDER BY privilege_type) AS privs
                           FROM information_schema.role_table_grants
                           WHERE table_schema = 'public' AND table_name = c.relname AND grantee IN ('anon', 'authenticated', 'service_role')
                           GROUP BY grantee) g), ''),
         E'\n' ORDER BY c.relname) AS sql
  FROM pg_class c WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'
),
fgrants AS (
  SELECT string_agg(
           format('REVOKE ALL ON FUNCTION public.%I(%s) FROM PUBLIC, anon, authenticated, service_role;', p.proname, pg_get_function_identity_arguments(p.oid)) ||
           coalesce(E'\n' || nullif(concat_ws(E'\n',
             CASE WHEN has_function_privilege('anon', p.oid, 'execute') THEN format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO anon;', p.proname, pg_get_function_identity_arguments(p.oid)) END,
             CASE WHEN has_function_privilege('authenticated', p.oid, 'execute') THEN format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO authenticated;', p.proname, pg_get_function_identity_arguments(p.oid)) END,
             CASE WHEN has_function_privilege('service_role', p.oid, 'execute') THEN format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO service_role;', p.proname, pg_get_function_identity_arguments(p.oid)) END
           ), ''), ''),
         E'\n' ORDER BY p.proname, p.oid) AS sql
  FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f', 'p')
),
pub AS (
  SELECT string_agg(format('ALTER PUBLICATION supabase_realtime ADD TABLE %I.%I;', schemaname, tablename), E'\n' ORDER BY tablename) AS sql
  FROM pg_publication_tables WHERE pubname = 'supabase_realtime' AND schemaname = 'public'
),
buckets AS (
  SELECT string_agg(format(
           'INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %L, %s, %s) ' ||
           'ON CONFLICT (id) DO UPDATE SET public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;',
           b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'NULL'),
           coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'NULL')),
         E'\n' ORDER BY b.id) AS sql
  FROM storage.buckets b
),
jobs AS (
  SELECT string_agg(format('SELECT cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command), E'\n' ORDER BY j.jobname) AS sql
  FROM cron.job j
)
SELECT concat_ws(E'\n\n',
  '-- Il Bel Paese: schema di partenza generato da migration/export/00_schema_ddl.sql il ' || to_char(now(), 'YYYY-MM-DD HH24:MI') || ' UTC',
  'BEGIN;',
  'SET check_function_bodies = off;',
  '-- Tipi',        (SELECT sql FROM enums),
  '-- Tabelle',     (SELECT sql FROM tabs),
  '-- Funzioni',    (SELECT sql FROM funcs),
  '-- Vincoli',     (SELECT sql FROM cons),
  '-- Indici',      (SELECT sql FROM idx),
  '-- RLS',         (SELECT sql FROM rls),
  '-- Policy',      (SELECT sql FROM pols),
  '-- Trigger',     (SELECT sql FROM trigs),
  '-- Permessi sulle tabelle',  (SELECT sql FROM tgrants),
  '-- Permessi sulle funzioni', (SELECT sql FROM fgrants),
  '-- Realtime',    (SELECT sql FROM pub),
  '-- Bucket dello storage', (SELECT sql FROM buckets),
  '-- Job pianificati (pg_cron)', (SELECT sql FROM jobs),
  'COMMIT;'
) AS baseline_sql;
